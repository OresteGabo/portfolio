"""Lossless transparent trimming for the RGBA8 PNGs emitted by our SVG renderer.

The generated bounds retain the original canvas and four transparent gutter pixels;
Compose can draw the smaller bitmap at its original position without moving pivots.
No resampling, color conversion or alpha quantization is performed.
"""
from pathlib import Path
import struct
import zlib

ROOT = Path(__file__).resolve().parents[1]
SIGNATURE = b'\x89PNG\r\n\x1a\n'


def chunks(data):
    if not data.startswith(SIGNATURE):
        raise ValueError('Expected PNG')
    offset = 8
    while offset < len(data):
        size = struct.unpack_from('>I', data, offset)[0]
        kind = data[offset + 4:offset + 8]
        body = data[offset + 8:offset + 8 + size]
        crc = struct.unpack_from('>I', data, offset + 8 + size)[0]
        if zlib.crc32(kind + body) & 0xffffffff != crc:
            raise ValueError('Invalid PNG checksum')
        yield kind, body
        offset += size + 12


def paeth(a, b, c):
    p = a + b - c
    distances = (abs(p - a), abs(p - b), abs(p - c))
    return (a, b, c)[distances.index(min(distances))]


def decode(data):
    parts = list(chunks(data))
    header = next(body for kind, body in parts if kind == b'IHDR')
    width, height, depth, color, compression, filtering, interlace = struct.unpack('>IIBBBBB', header)
    if (depth, color, compression, filtering, interlace) != (8, 6, 0, 0, 0):
        raise ValueError('Expected non-interlaced RGBA8 PNG from rsvg-convert')
    stride = width * 4
    raw = zlib.decompress(b''.join(body for kind, body in parts if kind == b'IDAT'))
    if len(raw) != (stride + 1) * height:
        raise ValueError('Unexpected PNG scanline length')
    rows = []
    previous = bytearray(stride)
    for y in range(height):
        start = y * (stride + 1)
        mode = raw[start]
        row = bytearray(raw[start + 1:start + 1 + stride])
        if mode not in range(5):
            raise ValueError('Unsupported PNG filter')
        if mode:
            for x in range(stride):
                left = row[x - 4] if x >= 4 else 0
                above = previous[x]
                upper_left = previous[x - 4] if x >= 4 else 0
                predictor = (0, left, above, (left + above) // 2, paeth(left, above, upper_left))[mode]
                row[x] = (row[x] + predictor) & 255
        rows.append(bytes(row))
        previous = row
    metadata = [(kind, body) for kind, body in parts if kind not in (b'IHDR', b'IDAT', b'IEND')]
    return width, height, rows, metadata


def chunk(kind, body):
    return struct.pack('>I', len(body)) + kind + body + struct.pack('>I', zlib.crc32(kind + body) & 0xffffffff)


def encode(width, height, rows, metadata=()):
    raw = bytearray()
    previous = bytes(width * 4)
    for row in rows:
        # None/Sub/Up cover the long flat/transparent runs in these illustrations.
        candidates = [row, bytes((value - (row[x - 4] if x >= 4 else 0)) & 255 for x, value in enumerate(row)),
                      bytes((value - previous[x]) & 255 for x, value in enumerate(row))]
        mode = min(range(3), key=lambda mode: sum(min(value, 256 - value) for value in candidates[mode]))
        raw.append(mode)
        raw.extend(candidates[mode])
        previous = row
    header = struct.pack('>IIBBBBB', width, height, 8, 6, 0, 0, 0)
    return (SIGNATURE + chunk(b'IHDR', header) + b''.join(chunk(kind, body) for kind, body in metadata)
            + chunk(b'IDAT', zlib.compress(bytes(raw), 9)) + chunk(b'IEND', b''))


def trim(data, gutter=4):
    width, height, rows, metadata = decode(data)
    occupied = [(y, [x for x in range(width) if row[x * 4 + 3]]) for y, row in enumerate(rows)]
    occupied = [(y, xs) for y, xs in occupied if xs]
    if not occupied:
        left = top = 0
        right = bottom = 1
    else:
        left = max(0, min(xs[0] for _, xs in occupied) - gutter)
        right = min(width, max(xs[-1] for _, xs in occupied) + 1 + gutter)
        top = max(0, occupied[0][0] - gutter)
        bottom = min(height, occupied[-1][0] + 1 + gutter)
    cropped = [row[left * 4:right * 4] for row in rows[top:bottom]]
    bounds = (width, height, left, top, right - left, bottom - top)
    return encode(right - left, bottom - top, cropped, metadata), bounds


def write_bounds(group, entries, check=False):
    function = 'onboarding' + group + 'Bounds'
    lines = ['package dev.orestegabo.portfolio.investments', '',
             '// Generated by the onboarding artwork scripts; preserves the original image canvas.',
             'import org.jetbrains.compose.resources.DrawableResource',
             'import portfolio.app.shared.generated.resources.*', '',
             f'internal fun {function}(resource: DrawableResource): OnboardingImageBounds? = when (resource) {{']
    for name, bounds in sorted(entries.items()):
        lines.append(f'    Res.drawable.{name} -> OnboardingImageBounds({", ".join(map(str, bounds))})')
    lines += ['    else -> null', '}', '']
    destination = ROOT / f'app/shared/src/commonMain/kotlin/dev/orestegabo/portfolio/investments/Onboarding{group}Bounds.generated.kt'
    expected = '\n'.join(lines)
    if check:
        if not destination.exists() or destination.read_text() != expected:
            raise SystemExit(f'Stale onboarding image bounds: {destination.name}')
    elif not destination.exists() or destination.read_text() != expected:
        destination.write_text(expected)
