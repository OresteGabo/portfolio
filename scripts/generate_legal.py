"""Generate offline app content and reviewable Markdown from docs/legal/content.json."""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
data = json.loads((ROOT / 'docs/legal/content.json').read_text())
def literal(value):
    return json.dumps(value, ensure_ascii=False).replace('$', r'\$')
def pair(value):
    return f'LegalText({literal(value["en"])}, {literal(value["fr"])})'
lines = ['package dev.orestegabo.portfolio.investments', '', '// Generated by scripts/generate_legal.py; edit docs/legal/content.json.',
         f'internal const val LEGAL_VERSION = {literal(data["version"])}', 'internal val legalDocuments = listOf(']
for doc in data['documents']:
    lines += [f'    LegalDocument({literal(doc["id"])}, {pair(doc["title"])}, {pair(doc["summary"])}, listOf(']
    for section in doc['sections']:
        lines += [f'        LegalSection({pair(section["title"])}, {pair(section["body"])}),']
    lines += ['    )),']
    for lang in ('en', 'fr'):
        text = '# ' + doc['title'][lang] + '\n\nGabo Portfolio · ' + data['version'] + '\n\n' + doc['summary'][lang] + '\n'
        for section in doc['sections']:
            text += '\n## ' + section['title'][lang] + '\n\n' + section['body'][lang] + '\n'
        (ROOT / f'docs/legal/{doc["id"]}.{lang}.md').write_text(text)
lines += [')', '']
(ROOT / 'app/shared/src/commonMain/kotlin/dev/orestegabo/portfolio/investments/LegalContent.generated.kt').write_text('\n'.join(lines))
